import fs from 'node:fs'
const kcss = fs.readFileSync('node_modules/katex/dist/katex.min.css', 'utf8')
const faces = [...kcss.matchAll(/@font-face\{([^}]*)\}/g)].map((m) => m[1])
let out = '/* generated by scripts/build-fonts.mjs — KaTeX (woff2 only) */\n'
for (const f of faces) {
  const fam = /font-family:([^;]+)/.exec(f)[1].replace(/"/g, '')
  const file = /url\(fonts\/([^)]+\.woff2)\)/.exec(f)[1]
  const weight = (/font-weight:([^;]+)/.exec(f) || [0, 'normal'])[1]
  const style = (/font-style:([^;]+)/.exec(f) || [0, 'normal'])[1]
  out += `@font-face{font-family:'${fam}';src:url(../assets/fonts/${file}) format('woff2');font-weight:${weight};font-style:${style};font-display:swap}\n`
}
const rest = kcss.replace(/@font-face\{[^}]*\}/g, '')
fs.writeFileSync('src/styles/katex-lite.css', out + rest)

// IBM Plex Sans Arabic
const ar = 'U+0600-06FF,U+0750-077F,U+0870-088E,U+0890-0891,U+0897-08E1,U+08E3-08FF,U+200C-200E,U+2010-2011,U+204F,U+2E41,U+FB50-FDFF,U+FE70-FE74,U+FE76-FEFC,U+102E0-102FB,U+10E60-10E7E,U+10EC2-10EC4,U+10EFC-10EFF,U+1EE00-1EEFF'
const la = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD'
let p = '/* generated — IBM Plex Sans Arabic + KaTeX digits/operators */\n'
for (const w of [400, 500, 600, 700]) {
  p += `@font-face{font-family:'IBM Plex Sans Arabic';font-style:normal;font-weight:${w};font-display:swap;src:url(../assets/fonts/ibm-plex-sans-arabic-arabic-${w}-normal.woff2) format('woff2');unicode-range:${ar}}\n`
  p += `@font-face{font-family:'IBM Plex Sans Arabic';font-style:normal;font-weight:${w};font-display:swap;src:url(../assets/fonts/ibm-plex-sans-arabic-latin-${w}-normal.woff2) format('woff2');unicode-range:${la}}\n`
}
// digits + math operators always render in the KaTeX face
const mathRange = 'U+0030-0039,U+002B,U+003D,U+00D7,U+2212,U+2192,U+00B7,U+2260'
p += `@font-face{font-family:'KaTeX Digits';src:url(../assets/fonts/KaTeX_Main-Regular.woff2) format('woff2');font-weight:100 599;font-style:normal;unicode-range:${mathRange};font-display:swap}\n`
p += `@font-face{font-family:'KaTeX Digits';src:url(../assets/fonts/KaTeX_Main-Bold.woff2) format('woff2');font-weight:600 900;font-style:normal;unicode-range:${mathRange};font-display:swap}\n`
fs.writeFileSync('src/styles/fonts.css', p)
console.log('ok', faces.length, 'katex faces')

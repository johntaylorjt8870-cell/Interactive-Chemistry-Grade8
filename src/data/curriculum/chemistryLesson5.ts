/* ---------- Block builders (platform vs textbook explicitly separated) ---------- */
const quote = (page: string, text: string, item?: string): ContentBlock => ({
  kind: 'textbook-verbatim',
  text,
  source: ref(page, item),
})
const bookQuestion = (questionId: string): ContentBlock => ({ kind: 'question', questionId, reveal: true })
const q = (...ids: string[]): ContentBlock[] => ids.map((id) => bookQuestion(id))
const practice = (questionId: string): ContentBlock => ({ kind: 'question', questionId, reveal: true })
const prose = (text: string): ContentBlock => ({ kind: 'paragraph', text, attribution: 'platform' })
const bullets = (items: string[]): ContentBlock => ({ kind: 'list', items, attribution: 'platform' })
const note = (title: string, text: string): ContentBlock => ({ kind: 'callout', tone: 'note', title, text, attribution: 'platform' })
const method = (title: string, text: string): ContentBlock => ({ kind: 'callout', tone: 'method', title, text, attribution: 'platform' })
const warning = (title: string, text: string): ContentBlock => ({ kind: 'callout', tone: 'warning', title, text, attribution: 'platform' })
const proc = (title: string, items: string[]): ContentBlock => ({ kind: 'procedure', title, items, attribution: 'platform' })
const tex = (expr: string, caption?: string): ContentBlock => ({ kind: 'formula', tex: expr, display: 'block', caption, attribution: 'platform' })
const table = (caption: string, columns: TableColumnSpec[], rows: TableRowSpec[], footnote?: string): ContentBlock => ({
  kind: 'table',
  caption,
  columns,
  rows,
  footnote,
  attribution: 'platform',
})


const source = (page: string, item?: string) => ({ page, item })

/* --- مساعدات كتل الحل: كلها شرح من إضافة المنصة، لا نص كتاب --------------- */

const prose = (text: string): ContentBlock => ({ kind: 'paragraph', text, attribution: 'platform' })
const method = (title: string, text: string): ContentBlock => ({
  kind: 'callout',
  tone: 'method',
  title,
  text,
  attribution: 'platform',
})
const warning = (title: string, text: string): ContentBlock => ({
  kind: 'callout',
  tone: 'warning',
  title,
  text,
  attribution: 'platform',
})
const formula = (tex: string, caption?: string): ContentBlock => ({
  kind: 'formula',
  tex,
  display: 'block',
  caption,
  attribution: 'platform',
})
const stepList = (title: string, items: string[]): ContentBlock => ({
  kind: 'procedure',
  title,
  items,
  attribution: 'platform',
})
const solutionTable = (
  caption: string,
  columns: Array<{ key: string; header: string; numeric?: boolean; rowHeader?: boolean }>,
  rows: Array<{ id: string; cells: Record<string, string> }>,
  footnote?: string,
): ContentBlock => ({ kind: 'table', caption, columns, rows, footnote, attribution: 'platform' })
const lewisMolecule = (
  leftSymbol: string,
  rightSymbol: string,
  sharedPairs: 1 | 2 | 3,
  leftLonePairSides: Array<'top' | 'right' | 'bottom' | 'left'>,
  rightLonePairSides: Array<'top' | 'right' | 'bottom' | 'left'>,
  caption: string,
): ContentBlock => ({
  kind: 'lewis-molecule',
  leftSymbol,
  rightSymbol,
  sharedPairs,
  leftLonePairSides,
  rightLonePairSides,
  caption,
  attribution: 'platform',
})
const equation = (
  reactants: string[],
  products: string[],
  caption: string,
): ContentBlock => ({
  kind: 'chemical-equation',
  reactants,
  products,
  caption,
  attribution: 'platform',
})


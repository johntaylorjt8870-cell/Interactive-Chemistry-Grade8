/* ---------- بناة الكتل مع فصل صريح بين نص الكتاب وإضافات المنصة ---------- */
const quote = (page: string, text: string, item?: string): ContentBlock => ({
  kind: 'textbook-verbatim',
  text,
  source: ref(page, item),
})

const ask = (...ids: string[]): ContentBlock[] =>
  ids.map((questionId) => ({ kind: 'question', questionId, reveal: true }))

const prose = (text: string): ContentBlock => ({
  kind: 'paragraph',
  text,
  attribution: 'platform',
})

const bullets = (items: string[], ordered = false): ContentBlock => ({
  kind: 'list',
  items,
  ordered,
  attribution: 'platform',
})

const note = (title: string, text: string): ContentBlock => ({
  kind: 'callout',
  tone: 'note',
  title,
  text,
  attribution: 'platform',
})

const method = (title: string, text: string): ContentBlock => ({
  kind: 'callout',
  tone: 'method',
  title,
  text,
  attribution: 'platform',
})

const warning = (title: string, text: string): ContentBlock => ({
  kind: 'callout',
  tone: 'warning',
  title,
  text,
  attribution: 'platform',
})

const proc = (title: string, items: string[]): ContentBlock => ({
  kind: 'procedure',
  title,
  items,
  attribution: 'platform',
})

const tex = (
  expr: string,
  caption?: string,
  attribution: 'textbook' | 'platform' = 'platform',
): ContentBlock => ({
  kind: 'formula',
  tex: expr,
  display: 'block',
  caption,
  attribution,
})

const table = (
  caption: string,
  columns: TableColumnSpec[],
  rows: TableRowSpec[],
  attribution: 'textbook' | 'platform' = 'platform',
  footnote?: string,
): ContentBlock => ({
  kind: 'table',
  caption,
  columns,
  rows,
  ...(footnote ? { footnote } : {}),
  attribution,
})


const ARABIC_INDIC = '٠١٢٣٤٥٦٧٨٩'
const arabicIndic = (value: number): string =>
  [...String(value)].map((digit) => ARABIC_INDIC[Number(digit)]!).join('')

const sourceRows: NotebookSourceRow[] = []

function registerItem(kind: string, citation: Lesson7Citation): string {
  const item = arabicIndic(sourceRows.length + 1)
  sourceRows.push({ item, kind, ...citation })
  return `${item} ـ `
}

const textItem = (kind: string, text: string, citation: Lesson7Citation): string =>
  `${registerItem(kind, citation)}${text}`

const defItem = (term: string, text: string, citation: Lesson7Citation): NotebookDefinition => ({
  term: `${registerItem('تعريف', citation)}${term}`,
  text,
  source: '',
})

const noteItem = (
  kind: string,
  text: string,
  citation: Lesson7Citation,
  tex?: string,
): NotebookNote => ({
  text: `${registerItem(kind, citation)}${text}`,
  ...(tex ? { notation: 'math' as const, tex } : {}),
})

const tableItem = (
  kind: string,
  caption: string,
  headers: string[],
  rows: string[][],
  citation: Lesson7Citation,
): NotebookTable => ({
  caption: `${registerItem(kind, citation)}${caption}`,
  columns: headers.map((header, colIndex) => ({
    key: `c${colIndex}`,
    header,
    ...(colIndex === 0 ? { rowHeader: true } : {}),
  })),
  rows: rows.map((cells, rowIndex) => ({
    id: `r${rowIndex}`,
    cells: Object.fromEntries(headers.map((_, colIndex) => [`c${colIndex}`, cells[colIndex] ?? ''])),
  })),
})

const figItem = (
  id: string,
  figureKey: Extract<NotebookFigure, { kind: 'lesson7-figure' }>['figureKey'],
  caption: string,
  citation: Lesson7Citation,
  kind = 'شكل توضيحي',
): NotebookFigure => ({
  id,
  kind: 'lesson7-figure',
  figureKey,
  caption: `${registerItem(kind, citation)}${caption}`,
})

const splitRow = (id: string): string[] => t(id).split(' | ')
const replaceBlank = (id: string): string[] =>
  splitRow(id).map((cell) => (cell === '[فارغ]' ? '……' : cell))


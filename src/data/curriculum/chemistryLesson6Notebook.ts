/** Keep the given line distinct from all student working (including the initial
 * symbolic translation of a word problem). No assessment controls or hidden answers. */
function problem(p: {
  ledger: string; question: string; name: string; prompt: string
  given?: string | NonNullable<NotebookNote['wordEquation']>
  skeleton?: string; reasoning: string[]; result: string; check: string
}): NotebookNote[] {
  const prompt = printedNote(`مسألة: ${p.name}`, book(p.ledger), p.prompt)
  const answer = solution(p.question)
  return [
    typeof p.given === 'string' ? math(prompt, p.given) : { ...prompt, wordEquation: p.given },
    ...(p.skeleton ? [math(workedNote(`ترجمة الرموز: ${p.name}`, answer, 'نكتب المعادلة الهيكلية بصيغ المواد وحالاتها، قبل ضبط المعاملات.'), p.skeleton)] : []),
    ...p.reasoning.map(text => workedNote(`خطوة حل: ${p.name}`, answer, text)),
    math(workedNote(`نتيجة وتحقّق: ${p.name}`, answer, p.check), p.result),
  ]
}

